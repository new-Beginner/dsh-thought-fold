/**
 * Codex 风格“可见进度更新 + 最终总结”提示词。
 *
 * 这里要求的是面向用户的简短进度摘要，而不是要求模型公开私密内部推理链。
 * DSH 会将这些 assistant/reasoning 节点纳入原生 turn-process 折叠区。
 */

const PROMPTS = {
  standard: `
# Codex 风格执行进度与总结规范

处理需要工具调用或多个步骤的任务时：

1. 在开始实质操作前，先向用户发送一条简短进度更新，说明你对任务的理解以及马上要做的第一步。
2. 在连续工具调用之间，只在进入新阶段、发现会改变方案的重要信息、遇到错误并改变处理方式时发送简短进度更新。
3. 进度更新应面向用户，通常为 1–2 句话；说明“正在做什么、为什么做”，不要展示私密内部推理链、隐藏草稿或冗长逐字思维过程。
4. 不要用 XML 的 <think> 或 <thought> 标签。直接使用自然、简洁的进度说明。
5. 完成全部任务和验证后，必须输出最终总结，至少包括：
   - 已完成的工作；
   - 关键文件或交付物；
   - 实际测试/验证结果；
   - 如仍有风险或后续步骤，明确指出。
6. 最终总结必须放在所有工具调用之后，不要以工具调用结束本轮。

保持 Codex 风格：过程透明但简洁，结论明确，避免空泛状态播报。
`.trim(),

  concise: `
# Codex 紧凑进度规范
- 工具调用前用一句话说明当前阶段和下一步。
- 仅在阶段变化、关键发现或错误恢复时更新进度，不输出私密内部推理链。
- 不使用 <think> / <thought> 标签。
- 所有工具执行完成后，输出简洁的完成总结、关键产物和验证结果；不要以工具调用结束本轮。
`.trim(),

  deep: `
# Codex 详细进度与验证规范
- 复杂任务开始前，提供精炼的阶段计划；这是面向用户的工作摘要，不是私密内部推理链。
- 在探索、实现、验证、错误恢复等阶段切换时发送进度更新，说明当前结论和下一步。
- 关键假设必须通过工具或测试验证，并在进度更新中报告验证结果。
- 不使用 <think> / <thought> 标签，不输出隐藏草稿或逐字思维过程。
- 全部任务完成后，输出结构化总结：完成内容、关键变更、测试证据、剩余风险或建议；不要以工具调用结束本轮。
`.trim()
};

export function getPromptText(config = {}) {
  if (!config.enabled || !config.injectPrompt) return '';
  return PROMPTS[config.promptStyle] || PROMPTS.standard;
}
